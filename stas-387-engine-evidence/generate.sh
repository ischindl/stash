#!/usr/bin/env bash
# STAS-387 evidence generator.
#
# Regenerates every raw capture this card's verdict rests on, from a clean
# checkout of the card worktree. Run it from anywhere:
#
#   bash stas-387-engine-evidence/generate.sh
#
# Determinism contract: every line is either derived from git state or
# normalised (volatile numbers masked), so a re-run reproduces the committed
# bytes. Raw unmasked process output stays in the ignored .fusion-tmp scratch
# dir and is never a deliverable.
#
# Measurement roots are named on every heading: R1 = this stash card worktree,
# R2 = engine trunk read through the sibling checkout's git dir, R3 = the live
# daemon process that runs this board, R4 = the persisted per-agent run logs
# and per-card task stores under the project .fusion directory.

