# --- R4: contamination scan ------------------------------------------------

{
  echo
  echo "# R4 surface scan: which stored files carry the reported literal at all"
  echo "# This scan builds the contamination ledger. It is NOT a search for the"
  echo "# incident: a hit here means the file quotes the literal, which for every"
  echo "# entry below is true because somebody wrote the report down."
  echo "# Scope note: .fusion-tmp is excluded. It sits outside version control and"
  echo "# holds this card's own scratch, including the forensic scripts that"
  echo "# reassemble the phrase, so scanning it would measure the card and not the"
  echo "# platform. Scanned surfaces: the worktree's evidence directory and the"
  echo "# store directories listed below."
  echo
  echo "command: grep -rlI '${LITERAL}' <root>"
  for root in "${WORKTREE_ROOT}" "${PROJECT_STORE}/memory" "${PROJECT_STORE}/agent-memory" "${PROJECT_STORE}/tasks" "${PROJECT_STORE}/agents" "${PROJECT_STORE}/artifacts" "${PROJECT_STORE}/logs"; do
    # --exclude-dir=STAS-387: this card's own attachments and registered artifacts
    # are copies of the evidence and therefore quote the literal. They are
    # reporters, not candidates -- scanning them would make every re-run find more
    # files than the last, because the card is still writing them.
    hits=$(grep -rlI "${LITERAL}" "${root}" --exclude-dir=.git --exclude-dir=.fusion-tmp --exclude-dir=STAS-387 2>"${SCRATCH}/grep-err.txt")
    if [ -z "${hits}" ]; then
      echo "  ${root}: 0 files"
    else
      echo "  ${root}: $(echo "${hits}" | wc -l) files"
      echo "${hits}" | sed 's/^/    /'
    fi
  done
  echo
  echo "## Ledger cross-check: every excluded entry in census-exclusions.txt must still carry the literal"
  while IFS= read -r entry; do
    case "${entry}" in
      store:*) resolved="${PROJECT_STORE}/${entry#store:}" ;;
      tree:*) resolved="${WORKTREE_ROOT}/${entry#tree:}" ;;
      *) continue ;;
    esac
    if [ -e "${resolved}" ]; then
      grep -cI "${LITERAL}" "${resolved}" >"${SCRATCH}/ledger.txt" 2>&1
      echo "  excluded_entry_ok ${entry} literal_lines=$(head -1 "${SCRATCH}/ledger.txt")"
    else
      echo "  excluded_entry_MISSING ${entry} -> ${resolved}"
    fi
  done <"${LEDGER}"
} >>"${RAW_DIR}/environment-census.txt"

