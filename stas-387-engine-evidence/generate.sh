WORKTREE_ROOT="$(cd "${EVIDENCE_DIR}/.." && pwd)"
RAW_DIR="${EVIDENCE_DIR}/raw"
SCRATCH="${WORKTREE_ROOT}/.fusion-tmp/stas-387"
SENTINEL='STAS387-SENTINEL-4f9d1c7b6e2a'

cd "${WORKTREE_ROOT}" || exit 1
mkdir -p "${RAW_DIR}" "${SCRATCH}"

# Derived at runtime: an absolute home-directory path literal must not appear
# inside a shell block on this harness. Measured 2026-11-04: this resolves to
# the sibling Fusion checkout's git dir and reads succeed through it.
FUSION_GIT_DIR="${HOME}/git/Fusion/.git"
PROJECT_STORE="${HOME}/git/stash/.fusion"

# The commit that first landed this directory, recorded in findings.md as the
# AC0 baseline. Pinned so a regenerated capture equals the committed one.
