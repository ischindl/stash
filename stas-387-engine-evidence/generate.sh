# --- helpers ---------------------------------------------------------------

# Byte-exact dumper. python3 is used rather than a byte-dump utility because
# the presence of xwd/od on this host is unprobed.
dump_bytes() {
  python3 - "$1" "$2" "$3" <<'PY'
import sys, pathlib
label, path, expected = sys.argv[1], sys.argv[2], sys.argv[3]
raw = pathlib.Path(path).read_bytes()
exp = expected.encode()
print(f"  {label}")
print(f"    expected_repr={exp!r}")
print(f"    captured_repr={raw!r}")
print(f"    expected_bytes={len(exp)} captured_bytes={len(raw)}")
print(f"    byte_equal={'YES' if raw == exp else 'NO -- THIS IS A REPRODUCTION'}")
PY
}

# Runs one sentinel shape. stdout is captured twice: to a file (what the shell
# really emitted) and to this tool's own result (what the model channel really
# shows). Candidate 1 is only visible in the second one.
sentinel_shape() {
  local label="$1"
  shift
  local out="${RAW_DIR}/.probe-out"
  local err="${RAW_DIR}/.probe-err"
  local rc=0
  "$@" >"${out}" 2>"${err}" || rc=$?
  echo "[$label]"
  printf '  command:'
  printf ' %q' "$@"
  printf '\n'
  echo "  exit_code=${rc}"
  dump_bytes "stdout-capture-file" "${out}" "${SENTINEL}
"
  if [ -s "${err}" ]; then
    echo "  stderr_repr=$(python3 -c 'import pathlib,re,sys;print(re.sub(rb"\([0-9]+\)", b"(PID)", pathlib.Path(sys.argv[1]).read_bytes()))' "${err}")"
  else
    echo "  stderr: empty"
  fi
  echo "  tool_channel_payload_between_markers"
  echo "  TOOL_CHANNEL_BEGIN"
  "$@"
  echo "  TOOL_CHANNEL_END"
}

# Prints the command it runs, its exit code and its first output line, so a
# capability claim carries its own instrument. Exit codes are read without a
# pipe, which would report the pipe's status instead.
probe_form() {
  local label="$1"
  shift
  echo "form: ${label}"
  printf '  command:'
  printf ' %q' "$@"
  printf '\n'
  local out="${SCRATCH}/probe.txt"
  local rc=0
  "$@" >"${out}" 2>&1 || rc=$?
  echo "  exit_code=${rc}"
  echo "  outcome_first_line=$(head -1 "${out}" | cut -c1-160)"
}

