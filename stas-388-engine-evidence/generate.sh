# raw/ac2-uniqueness.txt — AC2's machine check run on its own, plus the guidance
# greps: the rule must appear in exactly one production module and in no guidance
# surface in either repository.
# ---------------------------------------------------------------------------
capture_uniqueness() {
  {
    echo "# AC2 uniqueness — generated by stas-388-engine-evidence/generate.sh"
    echo
    echo "## the whole test file at the delivered tip, with the two uniqueness tests named"
    echo "(the file runs unfiltered, so the counters carry no skipped test)"
    echo "\$ vitest run src/__tests__/tool-result-authority.test.ts --reporter=verbose"
    if require_checkout; then
      (
        cd "$ENGINE_CHECKOUT/$PKG"
        NO_COLOR=1 ./node_modules/.bin/vitest run src/__tests__/tool-result-authority.test.ts \
          --reporter=verbose 2>&1 \
          | grep -aE '(uniqueness|only production source|label list alone|Test Files|      Tests )' \
          | sed -E 's/ [0-9]+ms$//' || true
      )
    else
      echo "  refused: no nested engine checkout"
    fi
    echo
    echo "## the production files that contain either marker (expected: exactly one each)"
    echo "invariant sentence:"
    git -C "$ENGINE_CHECKOUT" grep -l -i 'zero authority' -- packages plugins \
      | grep -av __tests__ | sed 's/^/  /' || true
    echo "directive-shape label list:"
    git -C "$ENGINE_CHECKOUT" grep -l -F 'DIRECTIVE_LABELS' -- packages plugins \
      | grep -av __tests__ | sed 's/^/  /' || true
    echo
    echo "## guidance surfaces, both repositories (expected: zero matches)"
    echo "This card wrote no sentence into any guidance file; enforcement is code."
    for root in "$CARD_ROOT" "$ENGINE_CHECKOUT"; do
      echo "root: $root"
      (
        cd "$root"
        for surface in CLAUDE.md AGENTS.md plugins stashai/plugin/assets; do
          if [ -e "$surface" ]; then
            echo "  surface present: $surface"
          else
            echo "  surface absent from this root: $surface"
          fi
        done
        grep -rn -iE 'zero authority|untrusted_tool_output|tool output is data' \
          CLAUDE.md AGENTS.md plugins stashai/plugin/assets 2>/dev/null \
          | grep -av node_modules | sed 's/^/  /' || true
        count="$(grep -rl -iE 'zero authority|untrusted_tool_output|tool output is data' \
          CLAUDE.md AGENTS.md plugins stashai/plugin/assets 2>/dev/null \
          | grep -avc node_modules || true)"
        echo "  matching files: ${count:-0}"
      )
    done
  } > "$RAW/ac2-uniqueness.txt"
}

