capture_attachment_check() {
  if ! require_checkout; then
    printf '%s\n' "# Attachment check — refused: no nested engine checkout" > "$RAW/ac4-attachment-check.txt"
    return
  fi

  base64 -d "$EVIDENCE_DIR/stas-388-engine.bundle.txt" > "$SCRATCH/roundtrip.bundle"
  {
    echo "# Attachment round trip — generated by stas-388-engine-evidence/generate.sh"
    echo
    echo "\$ base64 -d stas-388-engine.bundle.txt > $SCRATCH/roundtrip.bundle"
    if cmp -s "$EVIDENCE_DIR/stas-388-engine.bundle" "$SCRATCH/roundtrip.bundle"; then
      echo "decoded bytes identical to stas-388-engine.bundle: YES"
    else
      echo "decoded bytes identical to stas-388-engine.bundle: NO"
