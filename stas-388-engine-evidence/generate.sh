    echo
    echo "recorded tip = $TIP_SHA"
    echo "head sha     = $(git bundle list-heads "$SCRATCH/roundtrip.bundle" | awk '{print $1}')"
    echo "head ref     = $(git bundle list-heads "$SCRATCH/roundtrip.bundle" | awk '{print $2}')"
    echo
    echo "# the attachment a reviewer decodes is the file above, attached to the"
    echo "# card as stas-388-engine.bundle.txt because the bundle extension itself is"
    echo "# refused by the attachment tool."
  } > "$RAW/ac4-attachment-check.txt"
  rm -f "$SCRATCH/roundtrip.bundle"
}

