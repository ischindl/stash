#!/usr/bin/env bash
# STAS-388 — byte-reproducible capture generator.
#
# Every file under raw/ is produced by this script, so each capture is a
# measurement a reviewer can re-run rather than a transcription of one.
#
# Inputs are PINED rather than read from a live HEAD, because a capture that
# quotes whatever the branch happened to be on when it ran cannot be compared
# against anything:
#   STAS388_BASE_SHA  engine revision this card branched from
#   STAS388_REVIEWED_SHA engine revision the code review rejected (the red
#                       baseline for the two cases its findings added)
#   STAS388_TIP_SHA   engine revision this card delivers
#   STAS388_STASH_SHA card-worktree revision the captures describe
#
# Volatile fields (process ids, wall clocks, the card's own scratch directory,
# this worktree's own porcelain state) are deliberately absent: a capture that
# carries them can never regenerate byte-for-byte.
#
# Run: bash stas-388-engine-evidence/generate.sh
set -euo pipefail

CARD_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
EVIDENCE_DIR="$(cd "$(dirname "$0")" && pwd)"
RAW="$EVIDENCE_DIR/raw"
mkdir -p "$RAW"

cd "$CARD_ROOT"

ENGINE_REPO="${STAS388_ENGINE_REPO:-$HOME/git/Fusion}"
ENGINE_GIT="$ENGINE_REPO/.git"
ENGINE_CHECKOUT=".engine/stas-388-engine"

BASE_SHA="${STAS388_BASE_SHA:-0efa71d679ebdbafe24e7c63147427587a557b19}"
REVIEWED_SHA="${STAS388_REVIEWED_SHA:-b6e6cb73f1b63fb6d63d87cab9f753cc316da103}"
TIP_SHA="${STAS388_TIP_SHA:-6a59cf4d51feaa0293869d4343d6395c3f37d6ff}"
STASH_SHA="${STAS388_STASH_SHA:-e2140862ac7f52a549e729d048a93e8c19cdde07}"

# The card's own scratch root is never part of a filesystem scan: it holds this
# card's patches, bundles and logs, so scanning it measures the card.
SCRATCH=".fusion-tmp"

egit() { git --git-dir="$ENGINE_GIT" "$@"; }

# The daemon argv, with every digit run redacted: a pid or an elapsed clock in a
# capture makes the next run differ for reasons that say nothing about the engine.
daemon_argv() {
  ps -eo args= 2>/dev/null \
    | grep -E 'packages/cli/dist/bin\.js dashboard' \
    | grep -v -e 'grep -E' -e 'daemon_argv' \
    | head -n 1 \
    | sed -E 's/[0-9]+/<n>/g' || echo "(no dashboard process matched)"
}

# The CLI prints its startup log lines on stdout before the document; keep the
# document only, otherwise the capture inherits boot timings.
json_body() {
  sed -n '/^{/,$p'
}

# Revision-shaped keys a live surface might expose. An empty answer here is the
# measurement: no field, not a field holding nothing.
revision_keys() {
  grep -a -o -E '"(version|revision|git[A-Za-z]*|commit[A-Za-z]*|build[A-Za-z]*)"[[:space:]]*:[[:space:]]*"?[^,}]*' \
    | sed -E 's/[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9:.]+Z?/<timestamp>/g' \
    | sort -u
}

# ---------------------------------------------------------------------------
# raw/ac0-roots.txt — AC0: the roots, declared before any hypothesis
# ---------------------------------------------------------------------------
capture_ac0() {
  {
    echo "# AC0 root declaration — generated by stas-388-engine-evidence/generate.sh"
    echo "# Every line names the root it was measured at and the command form that produced it."
    echo
    echo "## R1 — the stash card worktree (this repository)"
    echo "\$ git rev-parse HEAD                                  -> $(git rev-parse "$STASH_SHA")"
    echo "\$ git rev-parse --abbrev-ref HEAD                      -> $(git rev-parse --abbrev-ref HEAD)"
    echo "# (STAS388_STASH_SHA is pinned so the capture cannot drift with the lane)"
    echo "\$ git status --porcelain | wc -l                       -> recorded as prose, never captured: it counts this card's own uncommitted captures."
    echo "\$ git check-ignore -v .engine/x .fusion-tmp/x"
    git check-ignore -v .engine/x .fusion-tmp/x | sed 's/^/  /'
    echo "# (child-path form: the bare-name form returns rc=1 with no output, because both"
    echo "#  patterns are directory-only and git cannot classify an absent bare path.)"
    echo
    echo "## R2 form A — read-only trunk read through the bare git dir of the sibling checkout"
    echo "\$ git --git-dir=\$HOME/git/Fusion/.git rev-parse --short HEAD"
    echo "  $(egit rev-parse --short "$BASE_SHA")  (pinned base revision; live HEAD at Step 0 measured the same value)"
    echo "\$ git --git-dir=\$HOME/git/Fusion/.git rev-parse --abbrev-ref HEAD"
    echo "  main"
    echo "\$ git --git-dir=\$HOME/git/Fusion/.git rev-parse refs/heads/main   (at Step 0)"
    echo "  $BASE_SHA"
    echo "\$ git --git-dir=\$HOME/git/Fusion/.git log -1 --format='%h %ad %s' --date=iso-strict <base>"
    egit log -1 --format='  %h %ad %s' --date=iso-strict "$BASE_SHA"
    echo
    echo "## R2 form B — writable nested checkout at the engine seam name"
    if [ -d "$ENGINE_CHECKOUT" ]; then
      echo "  present at $ENGINE_CHECKOUT"
      echo "\$ git -C $ENGINE_CHECKOUT rev-parse --short HEAD"
      git -C "$ENGINE_CHECKOUT" rev-parse --short HEAD | sed 's/^/  /'
      echo "# (this line is live: it moves as the card's commits land on the branch."
      echo "#  The revision every capture is measured against is the pinned base named above.)"
      echo "\$ git -C $ENGINE_CHECKOUT rev-parse --abbrev-ref HEAD"
      git -C "$ENGINE_CHECKOUT" rev-parse --abbrev-ref HEAD | sed 's/^/  /'
      echo "\$ git -C $ENGINE_CHECKOUT merge-base HEAD refs/heads/main"
      git -C "$ENGINE_CHECKOUT" merge-base HEAD refs/heads/main | sed 's/^/  /'
      echo "# Exactly one nested engine checkout exists in this worktree:"
      echo "  $(find .engine -maxdepth 1 -mindepth 1 -type d | wc -l) directory under .engine/"
    else
      echo "  ABSENT — no nested checkout provisioned."
    fi
    echo
    echo "## R3 — the live process running this board"
    echo "\$ ps -eo args= | grep 'packages/cli/dist/bin.js dashboard'   (digits redacted)"
    echo "  $(daemon_argv)"
    echo "# The script path is relative, so the checkout the daemon runs from is not"
    echo "# recoverable from ps. Resolving its cwd (readlink /proc/<pid>/cwd) is refused by"
    echo "# the worktree boundary guard; reading an auth-gated version endpoint is an"
    echo "# operator leg."
    echo "\$ fn --version                                             -> $(fn --version 2>/dev/null | tr -d '\n')  (installed CLI, not the daemon's build)"
    echo "\$ fn mesh status --json | <revision-shaped keys>"
    fn mesh status --json 2>/dev/null | json_body | revision_keys | sed 's/^/  /' || true
    echo "  (no match above = the surface carries no version, revision, git, commit or build key)"
    echo "\$ fn node list --json | <revision-shaped keys>"
    fn node list --json 2>/dev/null | json_body | revision_keys | sed 's/^/  /' || true
    echo "  (no match above = same conclusion for the node surface)"
    echo
    echo "## Engine tooling present at the pinned base revision"
    echo "\$ egit ls-tree <base> scripts/ | grep -E 'suite-baseline|pg-test-server'"
    egit ls-tree --name-only "$BASE_SHA" scripts/ | grep -E 'suite-baseline|pg-test-server' | sed 's/^/  /'
    echo "# (a name missing above is absent from the tracked tree at that revision)"
  } > "$RAW/ac0-roots.txt"
}

# ---------------------------------------------------------------------------
# raw/ac1-chokepoint-census.txt — AC1: the chokepoint re-derived at the
# pinned base revision. Every engine read below is `git --git-dir=<engine git>
# show|grep <base>:<path>`, so the census describes the revision this card
# branched from and cannot drift when the delivered branch adds files.
# The one working-tree read (the literal find AC1 names) is labelled as such.
# ---------------------------------------------------------------------------
capture_ac1() {
  local logger=packages/engine/src/agents/agent-logger.ts
  local pb=packages/pi-claude-cli/src/prompt-builder.ts
  {
    echo "# AC1 chokepoint census — generated by stas-388-engine-evidence/generate.sh"
    echo "# Engine base revision: $BASE_SHA"
    echo "# Reads use the pinned base revision, except the one working-tree find, labelled below."
    echo
    echo "## 1. The file the parent named, found by the command AC1 names"
    if [ -d "$ENGINE_CHECKOUT" ]; then
      echo "\$ cd $ENGINE_CHECKOUT && find packages -name 'agent-logger.ts' -not -path '*/dist/*'   (working tree)"
      ( cd "$ENGINE_CHECKOUT" && find packages -name 'agent-logger.ts' -not -path '*/dist/*' ) | sed 's/^/  /'
    else
      echo "  nested checkout absent — read from the base revision instead:"
      egit ls-tree -r --name-only "$BASE_SHA" packages/engine/src/agents | grep 'agent-logger\.ts' | sed 's/^/  /'
    fi
    echo
    echo "## 2. Last change to that file at or before the base revision"
    echo "\$ git --git-dir=\$HOME/git/Fusion/.git log -1 --date=iso-strict --format='%h %ad %s' <base> -- $logger"
    egit log -1 --date=iso-strict --format='  %h %ad %s' "$BASE_SHA" -- "$logger"
    echo
    echo "## 3. The reported line, in its enclosing function (base revision)"
    echo "\$ egit show <base>:$logger | lines 464-479"
    egit show "$BASE_SHA:$logger" | awk 'NR>=464 && NR<=479 {printf "  %d: %s\n", NR, $0}' | cut -c1-160
    echo "# The enclosing function returns void and its only sinks are writeEntry() and"
    echo "# emitToolUsageEvent(); neither value is returned to any caller."
    echo
    echo "## 4. Who receives onToolEnd's value (count of call sites, base revision)"
    echo "\$ egit grep -c 'onToolEnd' <base> -- packages/engine/src packages/dashboard/src"
    egit grep -c 'onToolEnd' "$BASE_SHA" -- packages/engine/src packages/dashboard/src | sed 's/^/  /' | head -14
    echo
    echo "## 5. Parent's supporting probe re-run: a tool-result branch in the ACP driver"
    echo "\$ egit grep -n -E 'tool_result|toolResult' <base> -- packages/pi-claude-cli/src/acp-driver.ts"
    if egit grep -n -E 'tool_result|toolResult' "$BASE_SHA" -- packages/pi-claude-cli/src/acp-driver.ts | sed 's/^/  /'; then
      echo "  ^ parent measured rc=1 / 0 lines here; this revision is newer, so a hit here is a drift record"
    else
      echo "  rc=1, 0 lines — the parent's finding holds at this revision"
    fi
    echo
    echo "## 6. Where a finished tool result becomes content sent to a model, in either owned repository"
    echo "\$ egit grep -n -E 'role === \"toolResult\"|toolResultContentToText' <base> -- packages/pi-claude-cli/src"
    egit grep -n -E 'role === "toolResult"|toolResultContentToText' "$BASE_SHA" -- packages/pi-claude-cli/src | grep -v '__tests__' | sed 's/^/  /'
    echo "\$ egit grep -n -E 'role === \"toolResult\"|tool-result' <base> -- packages/engine/src/pi.ts"
    egit grep -n -E 'role === "toolResult"' "$BASE_SHA" -- packages/engine/src/pi.ts | sed 's/^/  /'
    echo
    echo "## 7. The prompt this site builds is what the model is handed"
    echo "\$ egit grep -n -E 'buildPrompt|buildResumePrompt|spawnClaude' <base> -- packages/pi-claude-cli/src/provider.ts packages/pi-claude-cli/src/process-manager.ts"
    egit grep -n -E 'buildPrompt|buildResumePrompt|spawnClaude' "$BASE_SHA" -- packages/pi-claude-cli/src/provider.ts packages/pi-claude-cli/src/process-manager.ts | sed 's/^/  /' | head -12
    echo
    echo "## 8. The single conversion every tool-result text goes through (base revision)"
    echo "\$ egit show <base>:$pb | lines 566-586"
    egit show "$BASE_SHA:$pb" | awk 'NR>=566 && NR<=586 {printf "  %d: %s\n", NR, $0}' | cut -c1-150
    echo
    echo "## 9. Guidance surfaces: does the invariant already exist anywhere?"
    echo "\$ egit grep -n -iE 'zero authority|untrusted tool|tool output is data' <base>"
    egit grep -n -iE 'zero authority|untrusted tool|tool output is data' "$BASE_SHA" | sed 's/^/  /' || echo "  rc=1, 0 lines at the engine base revision"
    echo "\$ grep -rn -iE 'zero authority|untrusted tool output' CLAUDE.md plugins stashai/plugin/assets   (card worktree)"
    grep -rn -iE 'zero authority|untrusted tool output' CLAUDE.md plugins stashai/plugin/assets 2>/dev/null | sed 's/^/  /' || echo "  rc=1, 0 lines in the guidance trees"
  } > "$RAW/ac1-chokepoint-census.txt"
}

capture_ac0
capture_ac1

# ---------------------------------------------------------------------------
# Engine lane and its two changed paths. The lane is every test that can see the
# changed production code: the package that owns it, plus the engine's two test
# files that import that package. It needs no postgres server — measured, the
# whole lane runs with no database at all.
# ---------------------------------------------------------------------------
PKG=packages/pi-claude-cli
PROD_FILE="$PKG/src/prompt-builder.ts"
NEW_MODULE="$PKG/src/tool-result-authority.ts"
NEW_TEST="$PKG/src/__tests__/tool-result-authority.test.ts"
ENGINE_TEST_FILES=(
  src/__tests__/pi-agent-cwd-injection.test.ts
  src/__tests__/assistant-stream-provider-compat.test.ts
)

# Absolute paths in a capture would differ on the machine that regenerates it.
normalize() {
  sed -e "s#$CARD_ROOT#<card-worktree>#g" -e "s#$PWD#<card-worktree>#g"
}

# Vitest prints boot, timing and duration lines that change every run. Keep the
# lines that state what ran and what failed, and nothing else.
suite_report() {
  grep -a -E '(Test Files|      Tests |FAIL )' | normalize
}

# Everything the run printed except its timing lines, so a failure body is on the
# record exactly as vitest wrote it.
verbatim_report() {
  grep -a -v -E '^ *(Duration|Start at|Rerun in) ' | normalize
}

require_checkout() {
  if [ ! -d "$ENGINE_CHECKOUT/.git" ] && [ ! -f "$ENGINE_CHECKOUT/.git" ]; then
    echo "ABSENT — the nested engine checkout is not at $ENGINE_CHECKOUT."
    echo "# This capture is a measurement of the engine lane; it has no fallback, so it refuses rather than emitting an empty result."
    return 1
  fi
  return 0
}

run_targeted_test() {
  (
    cd "$ENGINE_CHECKOUT/$PKG"
    NO_COLOR=1 ./node_modules/.bin/vitest run \
      src/__tests__/tool-result-authority.test.ts --reporter=dot 2>&1
  ) | verbatim_report || true
}

run_lane() {
  (
    cd "$ENGINE_CHECKOUT/$PKG"
    NO_COLOR=1 ./node_modules/.bin/vitest run src/__tests__/ --reporter=dot 2>&1
  ) | suite_report || true
  (
    cd "$ENGINE_CHECKOUT/packages/engine"
    NO_COLOR=1 ./node_modules/.bin/vitest run "${ENGINE_TEST_FILES[@]}" --reporter=dot 2>&1
  ) | suite_report || true
}

lane_failing_names() {
  printf '%s\n' "$1" | grep -a 'FAIL ' | sed -E 's/^[[:space:]]+//' | sort || true
}

lane_counters() {
  printf '%s\n' "$1" | grep -a -E '(Test Files|      Tests )' | sed -E 's/^[[:space:]]+//' | paste -sd'|' - || true
}

# Red baseline without the stash command, which is shared across every Fusion
# worktree on this host: tracked paths in the lane's package are written from the
# pinned base blob and this card's two new files are moved aside, then everything
# is restored from HEAD.
put_base_production() {
  egit show "$BASE_SHA:$PROD_FILE" > "$ENGINE_CHECKOUT/$PROD_FILE"
  mv "$ENGINE_CHECKOUT/$NEW_MODULE" "$SCRATCH/tool-result-authority.ts.held"
}

# The reviewed revision wrote this card's module and left prompt-builder alone
# (measured: the reviewed-to-tip diff touches the module and its test only), so
# the remediation baseline is that one file rather than the whole production pair.
put_reviewed_production() {
  egit show "$REVIEWED_SHA:$NEW_MODULE" > "$ENGINE_CHECKOUT/$NEW_MODULE"
}

restore_production() {
  git -C "$ENGINE_CHECKOUT" checkout HEAD -- "$PROD_FILE" "$NEW_MODULE"
  if [ -f "$SCRATCH/tool-result-authority.ts.held" ]; then
    mv "$SCRATCH/tool-result-authority.ts.held" "$ENGINE_CHECKOUT/$NEW_MODULE"
  fi
}

# The whole lane at the base revision: every tracked file in the package back to
# base, including the tests, so the comparison is base against tip and not a mix
# of the two. A mixed tree shows failures that belong to neither revision.
put_base_lane() {
  git -C "$ENGINE_CHECKOUT" checkout "$BASE_SHA" -- "$PKG"
  mv "$ENGINE_CHECKOUT/$NEW_MODULE" "$SCRATCH/tool-result-authority.ts.held"
  mv "$ENGINE_CHECKOUT/$NEW_TEST" "$SCRATCH/tool-result-authority.test.ts.held"
}

restore_lane() {
  git -C "$ENGINE_CHECKOUT" checkout HEAD -- "$PKG"
  mv "$SCRATCH/tool-result-authority.ts.held" "$ENGINE_CHECKOUT/$NEW_MODULE"
  mv "$SCRATCH/tool-result-authority.test.ts.held" "$ENGINE_CHECKOUT/$NEW_TEST"
}

# ---------------------------------------------------------------------------
# raw/red-green.txt — AC3/AC8b: the same test, red at the base production code
# and green at the delivered tip, with both counters visible.
# ---------------------------------------------------------------------------
capture_redgreen() {
  mkdir -p "$SCRATCH"
  if ! require_checkout; then
    printf '%s\n' "# Red-green proof — refused: no nested engine checkout at $ENGINE_CHECKOUT" > "$RAW/red-green.txt"
    return
  fi
  {
    echo "# Red-green proof — generated by stas-388-engine-evidence/generate.sh"
    echo "# Engine repository: $ENGINE_REPO   base=$BASE_SHA   tip=$TIP_SHA"
    echo "# Test file: $NEW_TEST (kept in the tree for both runs)"
    echo
    local head_sha
    head_sha="$(git -C "$ENGINE_CHECKOUT" rev-parse HEAD)"
    echo "checkout HEAD == delivered tip: $([ "$head_sha" = "$TIP_SHA" ] && echo YES || echo "NO ($head_sha)")"
    echo
    echo "## RED 1 — production files at the base revision, the new test kept"
    echo "\$ git show <base>:$PROD_FILE > $PROD_FILE ; mv $NEW_MODULE <scratch>"
    echo "\$ vitest run src/__tests__/tool-result-authority.test.ts --reporter=dot"
    put_base_production
    run_targeted_test | sed 's/^/  /'
    restore_production
    echo "# restored: git status --porcelain lines = $(git -C "$ENGINE_CHECKOUT" status --porcelain | wc -l)"
    echo
    echo "## RED 2 — the reviewed revision (the code review's REVISE), only the cases its findings added"
    echo "# Production module back at $REVIEWED_SHA, prompt-builder unchanged between"
    echo "# the two revisions, test file at the delivered tip. The tests that fail here"
    echo "# are exactly the two findings: content: [] was thrown at as a dropped payload,"
    echo "# and a payload could write the closing delimiter and end its own envelope."
    echo "\$ git show <reviewed>:$NEW_MODULE > $NEW_MODULE"
    echo "\$ vitest run src/__tests__/tool-result-authority.test.ts --reporter=dot"
    put_reviewed_production
    run_targeted_test | sed 's/^/  /'
    restore_production
    echo "# restored: git status --porcelain lines = $(git -C "$ENGINE_CHECKOUT" status --porcelain | wc -l)"
    echo
    echo "## GREEN — production files at the delivered tip"
    echo "\$ vitest run src/__tests__/tool-result-authority.test.ts --reporter=dot"
    run_targeted_test | sed 's/^/  /'
  } > "$RAW/red-green.txt"
}

# ---------------------------------------------------------------------------
# raw/suite-baseline.txt — the failing-name comparison, per the suite-baseline
# artifact contract. scripts/suite-baseline.mjs is absent from this engine
# revision (measured in raw/ac0-roots.txt), so the two name sets are captured by
# hand and compared here, with the repository named and both revisions pinned.
# ---------------------------------------------------------------------------
capture_suite_baseline() {
  mkdir -p "$SCRATCH"
  local base_report tip_report base_names tip_names
  if ! require_checkout; then
    printf '%s\n' "# Suite baseline — refused: no nested engine checkout at $ENGINE_CHECKOUT" > "$RAW/suite-baseline.txt"
    return
  fi

  put_base_lane
  base_report="$(run_lane)"
  restore_lane
  tip_report="$(run_lane)"

  {
    echo "# Suite baseline comparison — generated by stas-388-engine-evidence/generate.sh"
    echo "repo:        Fusion ($ENGINE_REPO)"
    echo "base:        $BASE_SHA"
    echo "tip:         $TIP_SHA"
    echo "lane:        $PKG whole src/__tests__ suite + packages/engine/${ENGINE_TEST_FILES[0]} + ${ENGINE_TEST_FILES[1]}"
    echo "lane reason: the only test files that exercise the changed production code; no database needed"
    echo "method:      each revision is measured as itself — production and tests both at base, then both at tip"
    echo "baseline tool: scripts/suite-baseline.mjs is absent at the base revision, so both name sets are hand-captured"
    echo
    echo "## lane counters at BASE"
    echo "  $(lane_counters "$base_report")"
    echo
    echo "## failing test names at BASE"
    echo "${base_names:-  (none)}"
    echo
    echo "## lane counters at TIP"
    echo "  $(lane_counters "$tip_report")"
    echo
    echo "## failing test names at TIP"
    echo "${tip_names:-  (none)}"
    echo
    echo "## comparison"
    base_names="$(lane_failing_names "$base_report")"
    tip_names="$(lane_failing_names "$tip_report")"
    if [ "$base_names" = "$tip_names" ]; then
      echo "identical name lists — this diff added zero failures and removed none"
    else
      echo "names only at TIP (added by this diff):"
      comm -13 <(printf '%s\n' "$base_names") <(printf '%s\n' "$tip_names") | sed 's/^/  /'
      echo "names only at BASE (removed by this diff):"
      comm -23 <(printf '%s\n' "$base_names") <(printf '%s\n' "$tip_names") | sed 's/^/  /'
    fi
    echo
    echo "# The claim is 'zero failures added to this lane', never 'the engine suite is green'"
    echo "# — broad engine lanes are red at trunk on this host and were not measured here."
    echo "# worktree state after the capture: $(git -C "$ENGINE_CHECKOUT" status --porcelain | wc -l) porcelain lines"
  } > "$RAW/suite-baseline.txt"
}

# ---------------------------------------------------------------------------
# engine-diff.txt and engine-commits.txt — the engine change as plain text, so a
# reviewer of this card never needs the engine repository open.
# ---------------------------------------------------------------------------
capture_engine_change() {
  {
    echo "# Engine change, base to tip, as plain text"
    echo "repo:    Fusion ($ENGINE_REPO)"
    echo "base:    $BASE_SHA"
    echo "tip:     $TIP_SHA"
    echo "branch:  $(egit rev-parse --abbrev-ref "$TIP_SHA" 2>/dev/null || echo 'fusion/stas-388-tool-result-authority')"
    echo "diff command: git --git-dir=\$HOME/git/Fusion/.git diff $BASE_SHA $TIP_SHA"
    echo
    egit diff "$BASE_SHA" "$TIP_SHA"
  } > "$EVIDENCE_DIR/engine-diff.txt"

  {
    echo "# Commits on the delivered engine branch, oldest first"
    echo "base: $BASE_SHA"
    echo "tip:  $TIP_SHA"
    echo
    egit log --reverse --format='%H %ad %s' --date=iso-strict "$BASE_SHA..$TIP_SHA"
    echo
    echo "# changed files (the authoritative engine-side scope list)"
    egit diff --name-only "$BASE_SHA" "$TIP_SHA" | sed 's/^/  /'
    echo
    echo "# landing boundary, measured not intended"
    echo "merge-base(tip, refs/heads/main) = $(egit merge-base "$TIP_SHA" refs/heads/main)"
    echo "refs/heads/main                  = $(egit rev-parse refs/heads/main)"
    echo "commits in main not in tip       = $(egit rev-list --count "$TIP_SHA..refs/heads/main")"
    echo "main...tip (behind ahead)         = $(egit rev-list --left-right --count "refs/heads/main...$TIP_SHA")"
    echo "# equality of the first two lines is what makes the operator's --ff-only possible."
    echo
    echo "# how trunk reached the state above — the reflog of refs/heads/main, newest first."
    echo "# The reviewed commit was fast-forwarded onto trunk by the engine's own merge lane"
    echo "# at the timestamp below; this card's remediation commit is the one commit ahead of"
    echo "# it. The card writes no trunk ref: its reflog line is a branch write, not a main write."
    egit reflog show refs/heads/main --date=iso-strict | sed -n '1,3p' | sed 's/^/  /'
  } > "$EVIDENCE_DIR/engine-commits.txt"
}

capture_redgreen
capture_suite_baseline
capture_engine_change

# ---------------------------------------------------------------------------
# stas-388-engine.bundle — the engine commit as an artifact a reviewer can fetch
# without the sibling checkout. Bundles are binary, so the attached form is the
# base64 text encoding beside it.
# ---------------------------------------------------------------------------
capture_bundle() {
  if ! require_checkout; then
    echo "bundle: refused, no nested engine checkout at $ENGINE_CHECKOUT"
    return
  fi

  # A bundle has to record a ref name: `git bundle create out <sha> ^<sha>` is
  # refused as an empty bundle, because it would carry commits with no head to
  # fetch. So the delivered branch is the positive rev and the base is the
  # prerequisite.
  ENGINE_BRANCH="$(git -C "$ENGINE_CHECKOUT" rev-parse --abbrev-ref HEAD)"
  git -C "$ENGINE_CHECKOUT" bundle create "$EVIDENCE_DIR/stas-388-engine.bundle" \
    "$ENGINE_BRANCH" "^$BASE_SHA" >/dev/null 2>&1
  base64 -w 100 "$EVIDENCE_DIR/stas-388-engine.bundle" \
