# ---------------------------------------------------------------------------
# raw/ac8-payload-shapes.txt — what actually produces an empty tool result, read
# at the delivered tip from the code that produces it. The code review's P0 asked
# for the producer behind `content: []`: these are its files and lines. Upstream
# reads are single-file greps against the one installed copy of each package, so
# the capture carries no install-hash path that would differ on another host.
# ---------------------------------------------------------------------------
capture_payload_shapes() {
  if ! require_checkout; then
    printf '%s\n' "# Payload shapes — refused: no nested engine checkout" > "$RAW/ac8-payload-shapes.txt"
    return
  fi

  local core mcp coding rel
  for pkg in pi-agent-core pi-mcp pi-coding-agent; do
    rel="$(cd "$ENGINE_CHECKOUT" && ls -d node_modules/.pnpm/@earendil-works+$pkg@*/node_modules/@earendil-works/$pkg 2>/dev/null | sed -n 1p)"
    case "$pkg" in
      pi-agent-core) core="$ENGINE_CHECKOUT/$rel" ;;
      pi-mcp) mcp="$ENGINE_CHECKOUT/$rel" ;;
      pi-coding-agent) coding="$ENGINE_CHECKOUT/$rel" ;;
    esac
    if [ -z "$rel" ] || [ ! -d "$ENGINE_CHECKOUT/$rel" ]; then
      printf '%s\n' "# Payload shapes — refused: @earendil-works/$pkg is not installed in the checkout." > "$RAW/ac8-payload-shapes.txt"
      return
    fi
  done

  {
    echo "# What produces an empty tool result — generated by stas-388-engine-evidence/generate.sh"
    echo "# Engine tip measured here: $(git -C "$ENGINE_CHECKOUT" rev-parse HEAD)"
    echo "# Each upstream package has exactly one installed copy; the glob is shown rather"
    echo "# than the resolved directory, whose peer-hash suffix is a property of this install."
    echo
    echo "## 1. pi's own loop writes content: [] deliberately, for a result with no content"
    echo "\$ grep -n -E 'function createToolResultMessage|content: finalized.result.content' \\"
    echo "    node_modules/.pnpm/@earendil-works+pi-agent-core@*/node_modules/@earendil-works/pi-agent-core/dist/agent-loop.js"
    grep -n -E 'function createToolResultMessage|content: finalized\.result\.content' "$core/dist/agent-loop.js" | sed 's/^/  /' || true
    echo "  # the comment above that assignment, verbatim:"
    grep -a 'Untyped tools\|so the null never enters' "$core/dist/agent-loop.js" | sed 's/^ */  /' || true
    echo
    echo "## 2. the MCP client defaults an omitted content to []"
    echo "\$ grep -n 'content: \[\]' node_modules/.pnpm/@earendil-works+pi-mcp@*/node_modules/@earendil-works/pi-mcp/dist/client.js"
    grep -n 'content: \[\]' "$mcp/dist/client.js" | sed 's/^/  /' || true
    echo
    echo "## 3. the engine plugin lane passes a plugin's content array through unfiltered"
    echo "\$ git grep -n 'content: result.content' -- packages/engine/src/plugins/plugin-runner.ts"
    git -C "$ENGINE_CHECKOUT" grep -n 'content: result\.content' -- packages/engine/src/plugins/plugin-runner.ts | sed 's/^/  /' || true
    echo "\$ git grep -n -A3 'interface PluginToolResult' -- packages/core/src/plugins/plugin-types.ts"
    git -C "$ENGINE_CHECKOUT" grep -n -A3 'interface PluginToolResult' -- packages/core/src/plugins/plugin-types.ts | sed 's/^/  /' || true
    echo "\$ git grep -n 'content: \[\]' -- packages/plugin-sdk/src/__tests__/index.test.ts"
    git -C "$ENGINE_CHECKOUT" grep -n 'content: \[\]' -- packages/plugin-sdk/src/__tests__/index.test.ts | sed 's/^/  /' || true
    echo
    echo "## 4. bash reports zero output as ONE EMPTY TEXT BLOCK, not as []"
    echo "\$ grep -n 'text: outputText' node_modules/.pnpm/@earendil-works+pi-coding-agent@*/node_modules/@earendil-works/pi-coding-agent/dist/core/tools/bash.js"
    grep -n 'text: outputText' "$coding/dist/core/tools/bash.js" | sed 's/^/  /' || true
    echo "# so for every other tool on this platform 'the command ran and printed nothing' IS"
    echo "# content: [] — which is the measurement that makes [] unable to carry a verdict."
    echo
    echo "## 5. what a throw inside the marking costs on this provider"
    echo "\$ git grep -n -B3 'Error: \${errMsg}' -- packages/pi-claude-cli/src/provider.ts"
    git -C "$ENGINE_CHECKOUT" grep -n -B3 'Error: \${errMsg}' -- packages/pi-claude-cli/src/provider.ts | sed 's/^/  /' || true
    echo "# a throw during prompt build ends the turn with that error string as the assistant's"
    echo "# text, while the [] toolResult stays in pi's session history, so the next full-"
    echo "# history build raises again: the session is unusable on this provider."
    echo
    echo "## 6. the three empty states, as the delivered module prints them"
    echo "\$ git grep -n -A5 'EMPTY_NOTICES = {' -- $NEW_MODULE"
    git -C "$ENGINE_CHECKOUT" grep -n -A5 'EMPTY_NOTICES = {' -- "$NEW_MODULE" | sed 's/^/  /' || true
    echo "# zero-bytes        = a text block was delivered and held nothing (the bash shape)"
    echo "# no-content-blocks = no text block at all (the [] shape); the wording names that"
    echo "#                     this site cannot tell the two causes apart — the AC8c limit"
    echo "# unreadable shape  = raises, and no text is returned"
  } > "$RAW/ac8-payload-shapes.txt"
}

